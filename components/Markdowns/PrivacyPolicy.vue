## 5. AI Inputs, AI Outputs, Retention, and Model Training

### 5.1 Processing to Provide AI Services

We process AI Inputs and AI Outputs to authenticate and route requests, provide model inference, return responses, maintain security and reliability, prevent abuse, troubleshoot customer-reported issues, and comply with law.

Depending on the model you select, we may transmit AI Inputs and related request data to an upstream model developer, inference host, or infrastructure provider. We require providers acting on our behalf to process such data under contractual restrictions and appropriate security and confidentiality obligations, subject to model-specific terms disclosed through the Service.

### 5.2 Default Content Retention

By default, 4EVERLAND does not retain the content of AI Inputs or AI Outputs after the inference response is completed, except:

1. for transient processing, buffering, caching, and system recovery necessary to deliver the request;
2. where you intentionally use a feature that stores content or request history;
3. where limited content is reasonably necessary to investigate a specific security, fraud, abuse, or technical incident;
4. where you ask us to retain or review content for support;
5. where an upstream model provider applies a disclosed retention period; or
6. where retention is required by law.

Transient copies used for request processing, buffering, and service recovery are ordinarily deleted or overwritten within 24 hours unless an exception above applies. If limited AI Input or AI Output content must be preserved to investigate a specific security, fraud, abuse, or technical incident, we retain it only for as long as reasonably necessary for that investigation and ordinarily for no longer than 30 days, unless law requires a longer period.

We retain non-content operational metadata—such as account or API-key identifier, selected model, timestamps, token counts, latency, charge amount, request status, and safety or security signals—for up to 12 months for billing, reliability, capacity planning, security, fraud prevention, dispute resolution, and legal compliance. We may retain billing and transaction records derived from this metadata for the longer period described in Section 9.

### 5.3 Model Training

4EVERLAND does not use customer AI Inputs or AI Outputs to train or fine-tune generative AI models without the customer’s express authorization.

We do not permit an upstream provider acting solely on our behalf to use AI Inputs or AI Outputs for its own model training unless:

- you have expressly opted in;
- the applicable model-specific terms clearly disclose that use before you select the model; or
- you are using a separately identified public, community, evaluation, or free Service for which such use is an explicit condition.

We may use aggregated or de-identified operational metrics that do not contain AI Input or AI Output content to measure performance, forecast demand, allocate capacity, detect abuse, and improve the Services.

### 5.4 Sensitive Information

